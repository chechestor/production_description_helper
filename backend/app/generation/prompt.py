def user_message(product: dict) -> str:
    return "Входные данные товара (JSON):\n" + json.dumps(product, ensure_ascii=False, indent=2)


def retry_message(violations: list[str], previous: dict | None) -> str:
    lines = ["Предыдущий ответ нарушил требования. Исправь и верни карточку целиком заново:"]
    lines += [f"- {v}" for v in violations]
    if previous is not None:
        lines += ["", "Предыдущий ответ:", json.dumps(previous, ensure_ascii=False, indent=2)]
    return "\n".join(lines)
